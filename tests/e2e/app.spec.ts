test('aksesibilitas semua halaman dan tampilan desktop',async({page})=>{
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'Assalamu’alaikum.'})).toBeVisible()
 await page.screenshot({path:'artifacts/beranda-desktop.png',fullPage:true})
 const routes=['home','path','lesson/syahadat','quiz','recall','readings','glossary','notes','settings']
 const violations:unknown[]=[]
 for (const route of routes){
  await page.goto('/#'+route)
  await expect(page.locator('#utama h1')).toBeVisible()
  const result=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
  violations.push(...result.violations.map(v=>({route,id:v.id,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))})))
 }
 expect(violations).toEqual([])
})

